/*
 * sort.h —— 排序模块的对外承诺（public interface）。
 *
 * 分两类：
 *   数组排序：冒泡、插入、快速（三数取中选基准 + Hoare 划分）；
 *   链表排序：链表插入排序、链表归并排序（作用在 list.h 的 List 上）。
 * 本模块只依赖 list.h 的公开接口来建链/遍历/打印，不包含 list.c。
 */
#ifndef SORT_H
#define SORT_H

#include <stddef.h> /* size_t */

#include "list.h" /* List / ListNode：链表排序需要 */

/* ------------------------------------------------------------------ */
/* 数组排序（int 升序，原地）                                          */
/* 约定：a 为 NULL 或 n < 2 时直接返回；n 为元素个数。                 */
/* ------------------------------------------------------------------ */

/* 冒泡排序：相邻逆序即交换；带 swapped 标志，某趟无交换即提前结束。
 * O(n^2) 时间、O(1) 空间，稳定。 */
void sort_bubble(int *a, size_t n);

/* 直接插入排序：把 a[i] 插入前面已排好的区间。
 * O(n^2) 时间、O(1) 空间，稳定；近乎有序时接近 O(n)。 */
void sort_insertion(int *a, size_t n);

/* 快速排序：三数取中选基准 + Hoare 划分；对已排序/逆序/大量重复元素都
 * 不会退化成 O(n^2) 的递归深度（递归只下探较短一侧，深 O(log n)）。
 * 平均 O(n log n)、最坏 O(n^2)（对抗性输入）、O(log n) 栈空间，不稳定。 */
void sort_quick(int *a, size_t n);

/* ------------------------------------------------------------------ */
/* 链表排序（作用在带头结点的 List 上，原地改指针，不新建结点）        */
/* 约定：l 为 NULL 或元素个数 < 2 时直接返回。                        */
/* ------------------------------------------------------------------ */

/* 链表插入排序：维护一条已排好的裸链，逐个把结点摘下来插到正确位置。
 * O(n^2) 时间、O(1) 额外空间，稳定。 */
void sort_list_insertion(List *l);

/* 链表归并排序：快慢指针找中点切两半，递归排序后归并。
 * O(n log n) 时间、O(log n) 递归栈，稳定；不需要额外数组。 */
void sort_list_merge(List *l);

/* ------------------------------------------------------------------ */
/* 检查（给测试和自检用）                                             */
/* ------------------------------------------------------------------ */

/* 数组是否升序（非严格）；a 为 NULL 或 n < 2 视为已排序。 */
bool sort_array_is_sorted(const int *a, size_t n);

/* 链表是否升序（非严格）；l 为 NULL 或元素个数 < 2 视为已排序。 */
bool sort_list_is_sorted(const List *l);

#endif /* SORT_H */
